from charts import _fig, _save, NAVY, RED


def _price_chart():
    """2013–2025 年末价格（对数坐标）；红点标注四次大回撤。"""
    import matplotlib.ticker as mt
    years = list(range(2013, 2026))
    price = [760, 320, 430, 960, 14160, 3740, 7190, 29000, 46300, 16500, 42300, 93400, 87700]
    fig, ax = _fig((9.0, 4.3))
    ax.plot(years, price, color=NAVY, lw=2.4, marker="o", ms=5)
    ax.set_yscale("log")
    ax.set_ylim(60, 400000)
    ax.yaxis.set_major_formatter(mt.FuncFormatter(lambda v, _: f"{v:,.0f}"))
    ax.set_xticks(years)
    ax.set_ylabel("年末价格（美元，对数坐标）", fontsize=12)
    marks = [(2014, 320, "2013–15\n−85%", (0, -11), "top"),
             (2018, 3740, "2017–18\n−84%", (0, -11), "top"),
             (2022, 16500, "2021–22\n−77%", (0, -11), "top"),
             (2025, 87700, "2025–26\n−52%", (-4, 11), "bottom")]
    for x, y, t, off, va in marks:
        ax.plot([x], [y], "o", color=RED, ms=9)
        ax.annotate(t, (x, y), textcoords="offset points", xytext=off, ha="center", va=va, fontsize=12,
                    color=RED, fontweight="bold")
    return _save(fig, "p8_price")


