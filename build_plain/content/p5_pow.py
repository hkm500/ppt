def _interval_chart():
    return bar('p5_interval',
               ['0–10分钟', '10–20', '20–30', '30–40', '40分钟以上'],
               _DATA['interval_pct'], ylabel='占比（%）', fmt='{:.1f}%',
               title='下一个区块出现所需时间的分布（平均10分钟）', figsize=(9.0, 4.0))


def _attack_chart():
    a = _DATA['attack']
    z = list(range(len(a['0.1'])))
    fig, ax = _fig((9.0, 4.0))
    ax.plot(z, a['0.1'], color=NAVY, lw=2.2, marker='o', ms=4, label='攻击者占10%算力')
    ax.plot(z, a['0.3'], color=RED, lw=2.2, marker='o', ms=4, label='攻击者占30%算力')
    ax.set_yscale('log')
    ax.set_xticks(z)
    ax.set_xlabel('确认数 z（攻击者落后的区块数）', fontsize=12)
    ax.set_ylabel('攻击者追上的概率（对数坐标）', fontsize=12)
    ax.annotate('6个确认：约0.024%', (6, a['0.1'][6]), textcoords='offset points', xytext=(12, 14),
                fontsize=12, color=RED, arrowprops=dict(arrowstyle='-', color=RED, lw=0.8))
    ax.plot([6], [a['0.1'][6]], 'o', color=RED, ms=7)
    ax.legend(frameon=False, fontsize=12, loc='lower left')
    return _save(fig, 'p5_attack')


